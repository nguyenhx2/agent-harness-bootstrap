#!/usr/bin/env bash
# guard-deps.sh
# Event: PreToolUse   Matcher: Edit|Write|Bash|PowerShell
# Flag: purpose_code
# Enforces: .claude/rules/security-privacy.md (supply chain)
# BLOCKS (exit 2) the three ways an agent changes what code the project runs without leaving a
# reviewable, reproducible trail:
#   1. Edit/Write of a lockfile (package-lock.json, yarn.lock, pnpm-lock.yaml, bun.lock(b),
#      npm-shrinkwrap.json, poetry.lock, Pipfile.lock, uv.lock, Cargo.lock, go.sum, Gemfile.lock,
#      composer.lock, packages.lock.json, gradle.lockfile). A lockfile is generated: a hand edit
#      produces integrity hashes nothing verified. Change the manifest and run the package manager.
#   2. Piping a download straight into an interpreter: `curl ... | sh`, `wget -O- ... | bash`,
#      `irm ... | iex`, `iex (iwr ...)`. Nothing on disk to review, nothing pinned.
#   3. Installing from an unpinned remote source: a VCS or URL spec (`git+https://...`,
#      `github:org/repo`, `https://.../pkg.tgz`) with no commit SHA or content hash, `go install
#      x@latest`, `cargo install --git` without `--rev`. Registry installs by name are NOT blocked:
#      those are what the lockfile exists to pin.
#
# WHY BLOCK, NOT WARN: each of these runs code that nobody reviewed, and by the time a warning is
# read the install script has already executed. Each message names the pinned alternative.
#
# PARITY CONTRACT: guard-deps.sh and guard-deps.ps1 must stay behaviorally EQUIVALENT.
#
# Contract: reads the PreToolUse JSON payload on stdin. exit 2 = BLOCK (reason on stderr, shown
# to Claude); exit 0 = allow. Fails OPEN on an unreadable payload.

json_fields() {
  local keys=("$@")
  JF=()
  if command -v jq >/dev/null 2>&1; then
    local k
    for k in "${keys[@]}"; do
      JF+=("$(printf '%s' "$payload" | jq -r --arg k "$k" 'getpath($k | split(".")) | if type == "string" or type == "boolean" or type == "number" then tostring else empty end' 2>/dev/null)")
    done
  elif command -v perl >/dev/null 2>&1; then
    while IFS= read -r -d '' v; do JF+=("$v"); done < <(
      printf '%s' "$payload" | perl -0777 -MJSON::PP -e '
        local $/; my $d = eval { decode_json(<STDIN>) };
        for my $k (@ARGV) {
          my $v = $d;
          if ($d) {
            for my $p (split /\./, $k) {
              $v = (ref($v) eq "HASH") ? $v->{$p} : undef;
              last unless defined $v;
            }
          } else { $v = undef; }
          my $o = "";
          if (defined $v) {
            if (ref($v) eq "JSON::PP::Boolean") { $o = $v ? "true" : "false"; }
            elsif (!ref $v) { $o = $v; }
          }
          print($o . "\0");
        }
      ' "${keys[@]}" 2>/dev/null
    )
  elif command -v python3 >/dev/null 2>&1; then
    while IFS= read -r -d '' v; do JF+=("$v"); done < <(
      printf '%s' "$payload" | python3 -c '
import json, sys
try: root = json.load(sys.stdin)
except Exception: root = None
out = []
for k in sys.argv[1:]:
    v = root
    for p in k.split("."):
        v = v.get(p) if isinstance(v, dict) else None
        if v is None: break
    if isinstance(v, bool): out.append("true" if v else "false")
    elif isinstance(v, (str, int, float)): out.append(str(v))
    else: out.append("")
sys.stdout.write("\0".join(out) + "\0")
' "${keys[@]}" 2>/dev/null
    )
  else
    echo "guard-deps: no jq/perl/python3 available to parse the hook payload; allowing." >&2
  fi
  local i
  for ((i = ${#JF[@]}; i < ${#keys[@]}; i++)); do JF+=(""); done
}

block() {
  echo "BLOCKED by guard-deps: $1" >&2
  exit 2
}

payload=$(cat)
json_fields tool_input.file_path tool_input.command

path="${JF[0]}"
cmd="${JF[1]}"

# --- 1. hand edits to a lockfile ------------------------------------------------------------
if [ -n "$path" ]; then
  base=$(printf '%s' "$path" | tr '\\' '/')
  base=${base##*/}
  case "$base" in
    package-lock.json|npm-shrinkwrap.json|yarn.lock|pnpm-lock.yaml|bun.lock|bun.lockb|poetry.lock|Pipfile.lock|uv.lock|Cargo.lock|go.sum|Gemfile.lock|composer.lock|packages.lock.json|gradle.lockfile)
      block "$base is generated by the package manager - a hand edit leaves integrity hashes nothing verified. Change the manifest (package.json, pyproject.toml, Cargo.toml, go.mod, ...) and run the package manager to regenerate the lockfile."
      ;;
  esac
  exit 0
fi

[ -z "$cmd" ] && exit 0

# --- 2. download piped into an interpreter ----------------------------------------------------
if printf '%s' "$cmd" | grep -Eiq '(curl|wget|iwr|irm|Invoke-WebRequest|Invoke-RestMethod)[^|]*\|[[:space:]]*(sudo[[:space:]]+)?(sh|bash|zsh|dash|python3?|node|perl|ruby|iex|Invoke-Expression|pwsh|powershell)([^a-zA-Z0-9_-]|$)'; then
  block "piping a download into an interpreter runs code nobody reviewed and nothing pins. Download the script to a file, read it, pin its version or checksum, then run it - or ask the user to."
fi
if printf '%s' "$cmd" | grep -Eiq '(iex|Invoke-Expression)[[:space:]]*\(?[[:space:]]*\(?[[:space:]]*(irm|iwr|Invoke-RestMethod|Invoke-WebRequest|New-Object)'; then
  block "Invoke-Expression on downloaded content runs code nobody reviewed. Save it to a file, read it, pin it, then run it - or ask the user to."
fi

# --- 3. installs from unpinned remote sources -------------------------------------------------
segments=$(printf '%s\n' "$cmd" | sed -E 's/(&&|\|\||;|\|)/\n/g')
while IFS= read -r seg; do
  # is this segment an install?
  printf '%s' "$seg" | grep -Eq '(^|[[:space:]/])(pip3?|uv|poetry|pipx|npm|yarn|pnpm|bun|cargo|go|gem|composer)[[:space:]]' || continue
  printf '%s' "$seg" | grep -Eq '(pip3?|pipx|uv pip)[[:space:]]+install|uv[[:space:]]+add|poetry[[:space:]]+add|npm[[:space:]]+(i|install|add)([[:space:]]|$)|yarn[[:space:]]+(add|global[[:space:]]+add)|pnpm[[:space:]]+(add|i|install)([[:space:]]|$)|bun[[:space:]]+(add|install|i)([[:space:]]|$)|cargo[[:space:]]+install|go[[:space:]]+(install|get)|gem[[:space:]]+install|composer[[:space:]]+require' || continue

  if printf '%s' "$seg" | grep -Eq 'go[[:space:]]+(install|get)[[:space:]].*@latest([^a-zA-Z0-9_.-]|$)'; then
    block "go install/get with @latest resolves to whatever was published last. Pin a version (module@v1.2.3)."
  fi
  if printf '%s' "$seg" | grep -Eq 'cargo[[:space:]]+install[[:space:]].*--git' && ! printf '%s' "$seg" | grep -Eq -- '--(rev|tag)([[:space:]=]|$)'; then
    block "cargo install --git without --rev or --tag builds whatever the default branch holds today. Add --rev <commit-sha>."
  fi
  # cargo pins a git source with a flag, not in the URL - the URL is checked above
  printf '%s' "$seg" | grep -Eq 'cargo[[:space:]]+install[[:space:]]' && continue

  set -f
  read -ra toks <<< "$seg"
  set +f
  for t in "${toks[@]}"; do
    t=${t#\"}; t=${t%\"}; t=${t#\'}; t=${t%\'}
    remote=0
    case "$t" in
      git+*|git://*|github:*|gitlab:*|bitbucket:*|http://*|https://*) remote=1 ;;
      *@git+*|*@http://*|*@https://*) remote=1 ;;
    esac
    [ "$remote" -eq 0 ] && continue
    # pinned: a commit SHA after @ or # at the end, or a content hash fragment
    printf '%s' "$t" | grep -Eq '[@#][0-9a-fA-F]{7,40}$' && continue
    printf '%s' "$t" | grep -Eq '#(sha256|sha384|sha512)=[0-9a-fA-F]+$' && continue
    printf '%s' "$t" | grep -Eq '#(sha256|sha384|sha512)=[0-9a-fA-F]+&' && continue
    block "'$t' installs from a remote source with no commit SHA or hash, so the next install can fetch different code. Pin it (git+https://host/org/repo@<commit-sha>, or a URL with #sha256=<hash>), or install a released version from the registry."
  done
done <<< "$segments"

exit 0
