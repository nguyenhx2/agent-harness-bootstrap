def port_all(target: pathlib.Path, tool: str,
             force: bool = False) -> list[tuple[str, pathlib.Path]]:
    """Emit every file `tool` needs and return [(status, path)], printing nothing.

    Split out of port() so the self-test can assert on the statuses themselves rather than on
    scraped stdout - a contract asserted through printed text is a contract that silently stops
    being asserted the day someone rewords the report.
    """
    claude = target / ".claude"
    rules = claude / "rules"
    hooks = claude / "hooks"
    if not rules.is_dir():
        raise SystemExit(f"no {rules} - scaffold the Claude harness first (run harness-bootstrap).")
    ext = "sh" if (hooks / "protect-secrets.sh").is_file() else "ps1"

    results: list[tuple[str, pathlib.Path]] = []
    if tool in ("cursor", "all"):
        results += port_cursor_rules(rules, target / ".cursor" / "rules", force)
        results += port_cursor_hooks(target / ".cursor" / "hooks", ext, force)
    if tool in ("codex", "all"):
        results += port_codex_hooks(hooks, target / ".codex", ext, force)
    return results


def port(target: pathlib.Path, tool: str, force: bool = False) -> int:
    """Port, report, and return the exit code: non-zero if anything is in CONFLICT."""
    results = port_all(target, tool, force)
    rel = {p: p.relative_to(target).as_posix() for _, p in results}

    if tool in ("cursor", "all"):
        nrules = sum(1 for _, p in results if p.suffix == ".mdc")
        adapter = next(rel[p] for _, p in results if p.name == "cursor-adapter.py")
        print(f"\nCursor:")
        print(f"  .cursor/rules/      {nrules} rules (.md -> .mdc, paths: -> globs:)")
        print(f"  .cursor/hooks.json  registers the beforeShellExecution / beforeReadFile adapter")
        print(f"  {adapter}  the adapter (Cursor payload -> harness hooks)")
        print(f"  note: Cursor's afterFileEdit is observational, so an edit to an Accepted ADR is")
        print(f"        flagged after the fact, not blocked before. Everything else blocks pre-hoc.")
        print(f"  note: guard-agent-spawn does not port - Cursor has no subagent-spawn hook point,")
        print(f"        so the spawn boundary is rules text there, not an enforced gate.")

    if tool in ("codex", "all"):
        h = next(rel[p] for _, p in results if p.parts[-2:] == (".codex", "hooks.json"))
        print(f"\nCodex:")
        print(f"  AGENTS.md           already generated by harness-bootstrap - Codex reads it natively")
        print(f"  {h}   registers the existing hooks (Codex payload == Claude payload)")
        print(f"  note: Codex routes file edits through apply_patch (path inside tool_input.command),")
        print(f"        so protect-adr is best-effort there; the Bash-based guards are exact.")
        print(f"  note: guard-agent-spawn does not port - Codex has no Agent tool, so the spawn")
        print(f"        boundary is rules text there, not an enforced gate.")

    # Same report shape as the scaffolder's, deliberately: one person runs both, and two different
    # vocabularies for the same four outcomes is how a KEPT gets read as a write.
    by = {k: sorted(rel[p] for s, p in results if s == k)
          for k in ("ADDED", "KEPT", "CONFLICT", "FORCED")}

    def show(label: str, items: list[str]) -> None:
        if not items:
            return
        print(f"\n{label} ({len(items)}):")
        for i in items:
            print(f"  {i}")

    show("ADDED", by["ADDED"])
    show("KEPT (already identical)", by["KEPT"])
    show("CONFLICT (exists and differs - not written)", by["CONFLICT"])
    show("OVERWRITTEN (--force)", by["FORCED"])
    print(f"\nSummary: {len(by['ADDED']) + len(by['FORCED'])} written, {len(by['KEPT'])} kept, "
          f"{len(by['CONFLICT'])} conflict"
          + (f", {len(by['FORCED'])} overwritten (--force)." if by["FORCED"] else "."))

    if by["CONFLICT"]:
        # Unlike the scaffolder, this IS an error. The scaffolder's conflicts are the expected
        # brownfield queue; a porter's conflicts mean the ported harness on disk is now part this
        # run and part something else, and a half-applied port that exits 0 is exactly the failure
        # this contract was added to stop - CI would go green over it.
        print("\nCONFLICT means the file differs from what this port would write and was LEFT ALONE.\n"
              "Reconcile it by hand, or re-run with --force for the files you have decided to\n"
              "replace. Exiting non-zero: a partially applied port must not read as a clean one.")
        return 1
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Port a scaffolded harness to Cursor or Codex.")
    ap.add_argument("--target", type=pathlib.Path, help="repo that already has a scaffolded .claude/")
    ap.add_argument("--tool", choices=["cursor", "codex", "all"], default="all")
    ap.add_argument("--force", action="store_true",
                    help="overwrite files that exist and differ (reported as FORCED)")
    ap.add_argument("--self-test", action="store_true", help="test the adapter on sample payloads")
    a = ap.parse_args()

    if a.self_test:
        print("Cursor adapter self-test:")
        return self_test()
    if not a.target:
        ap.error("--target is required unless --self-test")
    return port(a.target.resolve(), a.tool, a.force)


if __name__ == "__main__":
    sys.exit(main())
