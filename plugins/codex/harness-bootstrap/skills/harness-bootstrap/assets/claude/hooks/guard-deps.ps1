# guard-deps.ps1
# Event: PreToolUse   Matcher: Edit|Write|Bash|PowerShell
# Flag: purpose_code
# Enforces: .claude/rules/security-privacy.md (supply chain)
# BLOCKS (exit 2):
#   1. Edit/Write of a lockfile - it is generated; change the manifest and run the package manager
#   2. a download piped into an interpreter (`curl | sh`, `irm | iex`, `iex (iwr ...)`)
#   3. an install from an unpinned remote source (VCS/URL spec without a commit SHA or hash,
#      `go install x@latest`, `cargo install --git` without --rev/--tag)
# Registry installs by name are NOT blocked: those are what the lockfile exists to pin.
#
# WHY BLOCK, NOT WARN: see guard-deps.sh - the install script has run before a warning is read.
#
# PARITY CONTRACT: guard-deps.sh and guard-deps.ps1 must stay behaviorally EQUIVALENT. Command
# patterns are case-sensitive except the download/interpreter names, which are case-insensitive
# in both (grep -Ei / -match).
#
# Contract: reads the PreToolUse JSON payload on stdin. exit 2 = BLOCK (reason on stderr, shown
# to Claude); exit 0 = allow. Fails OPEN on an unreadable payload.

try {
    $raw = [Console]::In.ReadToEnd()
    if (-not $raw) { exit 0 }
} catch {
    exit 0
}

# --- fast path: decide the common case without ConvertFrom-Json -------------------------------
# This hook starts on every shell call. ConvertFrom-Json loads a module, about a fifth of the run
# on Windows PowerShell 5.1, and most commands can never be blocked here - so that case is decided
# from the raw text first. Get-FastString returns one string field decoded EXACTLY, or $null: the
# key must occur once, and the value must be printable ASCII using no JSON escape but \" \\ \n \r
# \t (everything JSON.stringify writes for such text). A hook may only exit 0 on it, and only on a
# test that is a necessary condition of every block it raises; $null or an exception falls
# through to the full parse, which is unchanged. Copied verbatim - see "Latency" in
# hooks/README.md.
function Get-FastString([string]$raw, [string]$key) {
    if ([regex]::Matches($raw, '"' + $key + '"\s*:').Count -ne 1) { return $null }
    $m = [regex]::Match($raw, '"' + $key + '"\s*:\s*"((?:[^"\\]|\\.)*)"')
    if (-not $m.Success) { return $null }
    $s = $m.Groups[1].Value
    if ($s -cmatch '[^\x20-\x7E]') { return $null }
    $s = $s.Replace('\\', [string][char]1)
    if ($s -cmatch '\\([^"nrt]|$)') { return $null }
    $s = $s.Replace('\"', '"').Replace('\n', "`n").Replace('\r', "`r").Replace('\t', "`t")
    return $s.Replace([string][char]1, '\')
}

# Every shell block below needs a download tool or Invoke-Expression (-match, as below) or a
# package manager name starting a word (-cmatch, the same test the install check opens with,
# widened to segment separators). A lockfile path takes the full path.
try {
    $fc = $null
    if (-not $raw.Contains('"file_path"')) { $fc = Get-FastString $raw 'command' }
    if ($null -ne $fc -and -not ($fc -match '(curl|wget|iwr|irm|Invoke-WebRequest|Invoke-RestMethod)' -or $fc -match '(iex|Invoke-Expression)' -or $fc -cmatch '(^|[\s/&|;])(pip3?|uv|poetry|pipx|npm|yarn|pnpm|bun|cargo|go|gem|composer)\s')) { exit 0 }
} catch { }

try {
    $payload = $raw | ConvertFrom-Json
} catch {
    exit 0
}

function Block([string]$why) {
    [Console]::Error.WriteLine("BLOCKED by guard-deps: $why")
    exit 2
}

$path = [string]$payload.tool_input.file_path
$cmd = [string]$payload.tool_input.command

# --- 1. hand edits to a lockfile ------------------------------------------------------------
if ($path) {
    $base = ($path -replace '\\', '/').Split('/')[-1]
    $locks = @('package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lock',
        'bun.lockb', 'poetry.lock', 'Pipfile.lock', 'uv.lock', 'Cargo.lock', 'go.sum', 'Gemfile.lock',
        'composer.lock', 'packages.lock.json', 'gradle.lockfile')
    if ($locks -ccontains $base) {
        Block "$base is generated by the package manager - a hand edit leaves integrity hashes nothing verified. Change the manifest (package.json, pyproject.toml, Cargo.toml, go.mod, ...) and run the package manager to regenerate the lockfile."
    }
    exit 0
}

if (-not $cmd) { exit 0 }

# --- 2. download piped into an interpreter ----------------------------------------------------
if ($cmd -match '(curl|wget|iwr|irm|Invoke-WebRequest|Invoke-RestMethod)[^|]*\|\s*(sudo\s+)?(sh|bash|zsh|dash|python3?|node|perl|ruby|iex|Invoke-Expression|pwsh|powershell)([^a-zA-Z0-9_-]|$)') {
    Block 'piping a download into an interpreter runs code nobody reviewed and nothing pins. Download the script to a file, read it, pin its version or checksum, then run it - or ask the user to.'
}
if ($cmd -match '(iex|Invoke-Expression)\s*\(?\s*\(?\s*(irm|iwr|Invoke-RestMethod|Invoke-WebRequest|New-Object)') {
    Block 'Invoke-Expression on downloaded content runs code nobody reviewed. Save it to a file, read it, pin it, then run it - or ask the user to.'
}

# --- 3. installs from unpinned remote sources -------------------------------------------------
$segments = $cmd -split '&&|\|\||;|\||\r?\n'
foreach ($seg in $segments) {
    if ($seg -cnotmatch '(^|[\s/])(pip3?|uv|poetry|pipx|npm|yarn|pnpm|bun|cargo|go|gem|composer)\s') { continue }
    if ($seg -cnotmatch '(pip3?|pipx|uv pip)\s+install|uv\s+add|poetry\s+add|npm\s+(i|install|add)(\s|$)|yarn\s+(add|global\s+add)|pnpm\s+(add|i|install)(\s|$)|bun\s+(add|install|i)(\s|$)|cargo\s+install|go\s+(install|get)|gem\s+install|composer\s+require') { continue }

    if ($seg -cmatch 'go\s+(install|get)\s.*@latest([^a-zA-Z0-9_.-]|$)') {
        Block 'go install/get with @latest resolves to whatever was published last. Pin a version (module@v1.2.3).'
    }
    if ($seg -cmatch 'cargo\s+install\s.*--git' -and $seg -cnotmatch '--(rev|tag)([\s=]|$)') {
        Block 'cargo install --git without --rev or --tag builds whatever the default branch holds today. Add --rev <commit-sha>.'
    }
    # cargo pins a git source with a flag, not in the URL - the URL is checked above
    if ($seg -cmatch 'cargo\s+install\s') { continue }

    foreach ($t in @($seg.Trim() -split '\s+' | Where-Object { $_ -ne '' })) {
        if ($t.StartsWith('"')) { $t = $t.Substring(1) }
        if ($t.EndsWith('"')) { $t = $t.Substring(0, $t.Length - 1) }
        if ($t.StartsWith("'")) { $t = $t.Substring(1) }
        if ($t.EndsWith("'")) { $t = $t.Substring(0, $t.Length - 1) }
        $remote = ($t -clike 'git+*' -or $t -clike 'git://*' -or $t -clike 'github:*' -or $t -clike 'gitlab:*' -or
            $t -clike 'bitbucket:*' -or $t -clike 'http://*' -or $t -clike 'https://*' -or
            $t -clike '*@git+*' -or $t -clike '*@http://*' -or $t -clike '*@https://*')
        if (-not $remote) { continue }
        if ($t -cmatch '[@#][0-9a-fA-F]{7,40}$') { continue }
        if ($t -cmatch '#(sha256|sha384|sha512)=[0-9a-fA-F]+$') { continue }
        if ($t -cmatch '#(sha256|sha384|sha512)=[0-9a-fA-F]+&') { continue }
        Block "'$t' installs from a remote source with no commit SHA or hash, so the next install can fetch different code. Pin it (git+https://host/org/repo@<commit-sha>, or a URL with #sha256=<hash>), or install a released version from the registry."
    }
}

exit 0
