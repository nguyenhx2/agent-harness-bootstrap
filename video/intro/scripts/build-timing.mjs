// Turn SCRIPT.md (or SCRIPT.ja.md) plus the voice's character alignment into src/timing.<lang>.json:
// when every caption cue is spoken, when every scene starts, and the intervals the music must duck
// under. No API call. Refuses to run when the script has changed since the narration was generated,
// because captions timed against a different recording are captions that lie.
//
//   node scripts/build-timing.mjs [en|ja]      # default: both
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {HERE, AUDIO, LANGS, TEMPO, readScript, narrationText, sha, alignmentFile} from './script.mjs';

const LEAD_IN = 1.0; // seconds of picture before the first word
const TAIL = 4.0; // end-card hold after the last word
const SCENE_LEAD = 0.35; // a scene's picture arrives just ahead of its first word


function build(lang) {
  const scenes = readScript(lang);
  const text = narrationText(scenes);
  const manifest = JSON.parse(readFileSync(path.join(AUDIO, 'ASSETS.json'), 'utf8'));
  if (manifest.narration?.[lang]?.text_sha256 !== sha(text)) {
    console.error(`  FAIL  ${lang}: the script no longer matches the cached narration. Regenerate the voice:`);
    console.error(`        bash render.sh --generate voice ${lang} --force`);
    process.exit(1);
  }
  const a = JSON.parse(readFileSync(alignmentFile(lang), 'utf8')).alignment;
  if (a.characters.join('') !== text) {
    console.error(`  FAIL  ${lang}: the alignment does not spell the narration text; regenerate the voice.`);
    process.exit(1);
  }
  const k = TEMPO[lang];
  const st = a.character_start_times_seconds.map((x) => x / k);
  const en = a.character_end_times_seconds.map((x) => x / k);
  const r = (x) => Math.round(x * 1000) / 1000;

  let pos = 0;
  const cues = [];
  for (const s of scenes) {
    for (const c of s.cues) {
      const i = text.indexOf(c, pos);
      if (i < 0) throw new Error(`cue not found in narration: ${c}`);
      const j = i + c.length - 1;
      // The alignment hands a sentence stop the whole pause that follows it (the Japanese voice
      // holds a 「。」 for up to a second). Spoken, the cue is over when the stop begins, so a
      // trailing stop counts for at most 0.3 s; otherwise the next scene could not lead the voice.
      const endT = /[。、.,!?」"]/.test(text[j]) ? Math.min(en[j], st[j] + 0.3) : en[j];
      cues.push({scene: s.id, text: c, start: r(LEAD_IN + st[i]), end: r(LEAD_IN + endT)});
      pos = j + 1;
    }
  }

  // Speech intervals: runs of non-space characters, merged across pauses shorter than 0.45 s, so
  // the music ducks under each phrase and breathes back up only in real gaps. Japanese sentence
  // stops are pauses too, so they split runs the way a space does.
  const speech = [];
  for (let q = 0; q < text.length; q++) {
    if (/[\s。、「」]/.test(text[q])) continue;
    const s0 = LEAD_IN + st[q];
    const e0 = LEAD_IN + en[q];
    const last = speech.at(-1);
    if (last && s0 - last[1] < 0.45) last[1] = Math.max(last[1], e0);
    else speech.push([s0, e0]);
  }

  const voiceEnd = LEAD_IN + en.at(-1);
  const total = r(voiceEnd + TAIL);
  const sceneTimes = scenes.map((s, n) => {
    const first = cues.find((c) => c.scene === s.id);
    if (n === 0) return {id: s.id, start: 0};
    // Lead the voice by SCENE_LEAD, but never cut before the previous scene's last word lands.
    const prevEnd = cues.filter((c) => c.scene === scenes[n - 1].id).at(-1).end;
    return {id: s.id, start: r(Math.max(first.start - SCENE_LEAD, (prevEnd + first.start) / 2))};
  });
  sceneTimes.forEach((s, n) => (s.end = n + 1 < sceneTimes.length ? sceneTimes[n + 1].start : total));

  // A caption stays up until the next one replaces it, but never lingers more than 0.8 s past its
  // last word, and never across a scene cut.
  cues.forEach((c, n) => {
    const next = cues[n + 1];
    const sceneEnd = sceneTimes.find((s) => s.id === c.scene).end;
    c.out = r(Math.min(next ? next.start : total, c.end + 0.8, sceneEnd));
  });

  const out = {
    comment: `Generated by scripts/build-timing.mjs from ${lang === 'en' ? 'SCRIPT.md' : `SCRIPT.${lang}.md`} and audio/${path.basename(alignmentFile(lang))}. Do not edit.`,
    lang,
    tempo: k,
    leadIn: LEAD_IN,
    voiceEnd: r(voiceEnd),
    total,
    scenes: sceneTimes,
    cues,
    speech: speech.map(([s, e]) => [r(s), r(e)]),
  };
  writeFileSync(path.join(HERE, 'src', `timing.${lang}.json`), JSON.stringify(out, null, 2) + '\n');
  console.log(`  timing  ${lang}: ${cues.length} cues, ${sceneTimes.length} scenes, ${speech.length} speech runs, ${total}s total`);
  return sceneTimes.map((s) => s.id).join(' ');
}

const want = process.argv.slice(2).filter((a) => LANGS.includes(a));
const ids = (want.length ? want : LANGS).map(build);
if (new Set(ids).size > 1) {
  console.error('  FAIL  the scripts do not have the same scenes in the same order:');
  for (const s of ids) console.error(`        ${s}`);
  process.exit(1);
}
